"""v001: версионирование схемы и перенос состояния под ключ ``game``.

До этой версии прототип писал плоский словарь без ``schema_version``: все поля
лежали в корне вперемешку с метаданными файла. Такие сейвы существуют, и
единственный способ их не потерять — считать их «версией 0» и поднять сюда.

Заодно появляется ``rng.counters``: прототип не сохранял состояние
случайности вовсе, поэтому старые партии продолжатся с нулевых счётчиков.
Прогресс (тик, деньги, seed) при этом сохраняется полностью — миграция обязана
сохранять прогресс, а не воспроизводить недостающее (SAVEFORMAT.md, §7).

ВЫПУЩЕНА. Не редактировать — только добавлять новую миграцию.
"""

from __future__ import annotations

FROM_VERSION = 0
TO_VERSION = 1
DESCRIPTION = "версионирование схемы, состояние переносится под ключ game"


def migrate(data: dict) -> dict:
    saved_at = data.get("saved_at", 0.0)
    return {
        "schema_version": TO_VERSION,
        "created_at": data.get("created_at", saved_at),
        "saved_at": saved_at,
        "game": {
            "seed": data.get("seed", 0),
            "tick": data.get("tick", 0),
            "epoch": data.get("epoch", saved_at),
            "speed": data.get("speed", "x1"),
            "company": {
                "name": data.get("company_name", "Модуль"),
                # Прототип хранил деньги дробным числом рублей. Это исправляет
                # следующая миграция; здесь только переносим как есть, чтобы
                # каждая ступень делала ровно одно изменение.
                "balance": data.get("balance", 0.0),
            },
            "rng": {"counters": {}},
        },
    }
