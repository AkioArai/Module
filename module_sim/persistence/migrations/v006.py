"""v006: рынок с почасовой ценой, договор PPA и топливо (фаза 2б).

Что добавляется:

* ``game.market`` — случайная часть цены (``noise``, ``demand_deviation``),
  три копилки начисленного, недопоставка по договору и сам договор;
* ``game.fuel`` — склад и состояние процесса цены топлива.

Тонкое место здесь ровно одно, и оно про деньги.

До этой версии выручка считалась как ``округлить(энергия × фиксированная
цена)``, а выплаченное хранилось в ``revenue_paid_cents``. Теперь причитающееся
считается из копилок начисленного, и расчёт платит **разницу** между
причитающимся и уже выплаченным. Если оставить копилки нулевыми, то в первом же
расчёте разница окажется равной минус всей выручке партии, и игра честно
спишет с компании всё, что она заработала за годы.

Поэтому старому сейву копилка спота выставляется равной уже выплаченному:
причитающееся совпадает с выплаченным, разница нулевая, и партия продолжается с
того же места. Прошлая выручка при этом считается спотовой целиком — договоров
до этой версии не существовало.

ВЫПУЩЕНА. Не редактировать — только добавлять новую миграцию.
"""

from __future__ import annotations

FROM_VERSION = 5
TO_VERSION = 6
DESCRIPTION = "рынок с суточным профилем цены, договор PPA, топливо с лагом поставки"

#: Стартовый склад для партии, начатой до фазы 2б: годовая потребность
#: (BALANCE.md, §4). Оставить старую партию с пустым складом было бы наказанием
#: за то, что она началась раньше, чем в игре появилось топливо.
DEFAULT_FUEL = {"stock_tons": 24.0, "price_noise": 0.0}


def migrate(data: dict) -> dict:
    game = data["game"]

    market = game.setdefault("market", {})
    paid = market.get("revenue_paid_cents", 0)
    market.setdefault("noise", 0.0)
    market.setdefault("demand_deviation", 0.0)
    # Вся прошлая выручка — спотовая: договоров до этой версии не было.
    market.setdefault("spot_accrued_cents", float(paid))
    market.setdefault("ppa_accrued_cents", 0.0)
    market.setdefault("penalty_accrued_cents", 0.0)
    market.setdefault("ppa_shortfall_mwh", 0.0)
    market.setdefault("ppa_shortfall_settled_mwh", 0.0)
    market.setdefault("ppa", None)

    game.setdefault("fuel", dict(DEFAULT_FUEL))
    return data
