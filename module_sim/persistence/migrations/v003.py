"""v003: в партии появляется очередь дискретных событий.

Добавляется ``game.scheduler`` — планировщик, вокруг которого построен батчевый
догон (DESIGN.md, §Р2). До этой версии очереди не было вовсе, поэтому старая
партия получает пустую: ничего запланированного в ней и не могло быть.

``next_order`` начинается с нуля по той же причине — номеров ещё никто не
выдавал.

ВЫПУЩЕНА. Не редактировать — только добавлять новую миграцию.
"""

from __future__ import annotations

FROM_VERSION = 2
TO_VERSION = 3
DESCRIPTION = "добавлена очередь дискретных событий game.scheduler"


def migrate(data: dict) -> dict:
    game = data["game"]
    # setdefault, а не присваивание: миграция не имеет права затереть данные,
    # если поле почему-то уже есть (SAVEFORMAT.md, §5, правило 5).
    game.setdefault("scheduler", {"events": [], "next_order": 0})
    return data
